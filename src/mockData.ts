export const calculateGrade = (quiz: number, test: number, exam: number) => {
  const q = Math.max(0, Math.min(100, Number(quiz) || 0));
  const t = Math.max(0, Math.min(100, Number(test) || 0));
  const e = Math.max(0, Math.min(100, Number(exam) || 0));
  const total = Math.round(q * 0.2 + t * 0.3 + e * 0.5);

  let letter = 'F';
  let remarks = 'Needs Improvement';
  if (total >= 90) {
    letter = 'A';
    remarks = 'Excellent';
  } else if (total >= 80) {
    letter = 'B';
    remarks = 'Very Good';
  } else if (total >= 70) {
    letter = 'C';
    remarks = 'Satisfactory';
  } else if (total >= 60) {
    letter = 'D';
    remarks = 'Pass';
  }

  return {
    quiz: q,
    test: t,
    exam: e,
    total,
    gradeLetter: letter,
    remarks,
  };
};

